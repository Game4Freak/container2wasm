// wit-bridge-gen generates the Rust source of the container2wasm bridge
// component (extras/wasip3/bridge) for a WIT world.
//
// Input is the JSON produced by `wasm-tools component wit --json <wit dir>`.
// Output files (in --out):
//
//	generated.rs     Rust code included by the bridge crate
//	world.wit        the composed world (user world + c2w:bridge/vm + wasi:cli/run)
//	description.json the resolve JSON, served to guest SDKs by the emulator
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	var (
		resolvePath = flag.String("resolve", "", "path to the JSON output of `wasm-tools component wit --json` (default: stdin)")
		worldName   = flag.String("world", "", "name of the world to bridge (default: the only world of the main package)")
		outDir      = flag.String("out", ".", "output directory")
	)
	flag.Parse()

	var data []byte
	var err error
	if *resolvePath == "" {
		data, err = readAll(os.Stdin)
	} else {
		data, err = os.ReadFile(*resolvePath)
	}
	if err != nil {
		fatalf("reading resolve JSON: %v", err)
	}
	var r Resolve
	if err := json.Unmarshal(data, &r); err != nil {
		fatalf("parsing resolve JSON: %v", err)
	}
	idx, err := selectWorld(&r, *worldName)
	if err != nil {
		fatalf("%v", err)
	}
	g := &generator{r: &r, world: &r.Worlds[idx], worldIdx: idx}
	if err := g.generate(); err != nil {
		fatalf("%v", err)
	}
	for _, w := range g.warnings {
		fmt.Fprintf(os.Stderr, "warning: %s\n", w)
	}
	if err := os.MkdirAll(*outDir, 0o755); err != nil {
		fatalf("%v", err)
	}
	if err := os.WriteFile(filepath.Join(*outDir, "generated.rs"), []byte(g.source()), 0o644); err != nil {
		fatalf("%v", err)
	}
	if err := os.WriteFile(filepath.Join(*outDir, "world.wit"), []byte(composedWorld(&r, idx)), 0o644); err != nil {
		fatalf("%v", err)
	}
	if err := os.WriteFile(filepath.Join(*outDir, "description.json"), data, 0o644); err != nil {
		fatalf("%v", err)
	}
}

func selectWorld(r *Resolve, name string) (int, error) {
	if len(r.Packages) == 0 {
		return 0, fmt.Errorf("no package found in the WIT input")
	}
	// The main package is the last one listed (dependencies come first).
	main := &r.Packages[len(r.Packages)-1]
	if name != "" {
		idx, ok := main.Worlds[name]
		if !ok {
			return 0, fmt.Errorf("world %q not found in package %s", name, main.Name)
		}
		return idx, nil
	}
	if len(main.Worlds) != 1 {
		var names []string
		for n := range main.Worlds {
			names = append(names, n)
		}
		return 0, fmt.Errorf("package %s defines %d worlds (%s); select one with --world", main.Name, len(main.Worlds), strings.Join(names, ", "))
	}
	for _, idx := range main.Worlds {
		return idx, nil
	}
	return 0, fmt.Errorf("unreachable")
}

func composedWorld(r *Resolve, idx int) string {
	w := &r.Worlds[idx]
	pkg := r.Packages[*w.Package].Name
	ns, name, version := pkgName(pkg)
	include := ns + ":" + name + "/" + w.Name
	if version != "" {
		include += "@" + version
	}
	return fmt.Sprintf(`// Generated by wit-bridge-gen. DO NOT EDIT.
package c2w:bridge-composed;

world bridge {
    include %s;
    import c2w:bridge/vm@0.1.0;
    export wasi:cli/run@0.3.0;
}
`, include)
}

func readAll(f *os.File) ([]byte, error) {
	var buf []byte
	tmp := make([]byte, 64*1024)
	for {
		n, err := f.Read(tmp)
		buf = append(buf, tmp[:n]...)
		if err != nil {
			if err.Error() == "EOF" {
				return buf, nil
			}
			return buf, err
		}
	}
}

func fatalf(format string, args ...interface{}) {
	fmt.Fprintf(os.Stderr, "wit-bridge-gen: "+format+"\n", args...)
	os.Exit(1)
}
