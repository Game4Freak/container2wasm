#!/bin/sh
# Generate c2w_pack_list.h for extras/wasip3/vmcore/c2w_pack.c.
#
# usage: gen-pack-list.sh <pack directory> > c2w_pack_list.h
#
# Every regular file in the directory is embedded and exposed as
# /pack/<file name>.
set -eu
dir="$1"
echo "/* generated by extras/wasip3/scripts/gen-pack-list.sh */"
echo "#define C2W_PACK_FILES \\"
for f in "$dir"/*; do
  [ -f "$f" ] || continue
  name=$(basename "$f")
  ident=$(printf '%s' "$name" | tr -c 'A-Za-z0-9_' '_')
  abs=$(cd "$(dirname "$f")" && pwd)/$name
  echo "  C2W_PACK_FILE(${ident}, \"${name}\", \"${abs}\") \\"
done
echo ""
